// ─────────────────────────────────────────────────────────────────────────────
//  helpers/gen-skin-themes.mjs
//  Generates src/data/skinThemes.js — one Forge palette + splash per champion.
//   • 10 CURATED champions keep hand-sampled palettes from a specific skin's
//     splash art (their `splash` is that skin's bundled file).
//   • Every other champion derives its palette from its own tuned color/glow
//     in the champ file, and uses its own BASE-skin splash (<dd>_0).
//  Also prints the list of base-skin splash files to fetch (all non-curated).
//  Run: node helpers/gen-skin-themes.mjs
// ─────────────────────────────────────────────────────────────────────────────
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const champDir = path.join(root, "src/data/champs");

// Hand-sampled from each skin's splash art (primary / highlight / accent).
const CURATED = {
  Ornn:     { skin: "The Forge",      m: "#E24A2A", h: "#FF8C42", a: "#8A1F24", splash: "Ornn_0" },
  Volibear: { skin: "Duality Dragon", m: "#2E7BE8", h: "#7FC0FF", a: "#E8C271", splash: "Volibear_7" },
  Pantheon: { skin: "Ruined",         m: "#22C7A6", h: "#7FF7DD", a: "#1B7A68", splash: "Pantheon_25" },
  Aatrox:   { skin: "Blood Moon",     m: "#C4202A", h: "#F0484A", a: "#7A1418", splash: "Aatrox_7" },
  Lillia:   { skin: "Spirit Blossom", m: "#9B6BE8", h: "#C79CFF", a: "#F072C5", splash: "Lillia_1" },
  Teemo:    { skin: "Little Devil",   m: "#D9242A", h: "#FF9E3D", a: "#8A4FA8", splash: "Teemo_14" },
  Yasuo:    { skin: "Nightbringer",   m: "#E86A1E", h: "#FFB35A", a: "#7A3410", splash: "Yasuo_9" },
  Jinx:     { skin: "Star Guardian",  m: "#E33A66", h: "#FF7E9C", a: "#8B4FBE", splash: "Jinx_4" },
  Kaisa:    { skin: "K/DA",           m: "#9A3FE8", h: "#C77BFF", a: "#E84AC4", splash: "Kaisa_14" },
  Zed:      { skin: "Galaxy Slayer",  m: "#C9A24A", h: "#FFD880", a: "#4A5BC8", splash: "Zed_13" },
};

const clamp = (n) => Math.max(0, Math.min(255, Math.round(n)));
const parse = (hex) => {
  let h = hex.replace("#", "");
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
const toHex = (rgb) => "#" + rgb.map((v) => clamp(v).toString(16).padStart(2, "0")).join("");
const lighten = (hex, f) => toHex(parse(hex).map((v) => v + (255 - v) * f));
const darken  = (hex, f) => toHex(parse(hex).map((v) => v * (1 - f)));

const files = fs.readdirSync(champDir).filter((f) => f.endsWith(".js") && f !== "index.js");
const entries = {};
const needSplash = [];

for (const f of files) {
  const src = fs.readFileSync(path.join(champDir, f), "utf8");
  const m = src.match(/dd:\s*"([^"]+)"[\s\S]*?color:\s*"(#[0-9a-fA-F]{3,8})"[\s\S]*?glow:\s*"(#[0-9a-fA-F]{3,8})"/);
  if (!m) { console.error("!! no dd/color/glow in", f); continue; }
  const [, dd, color, glow] = m;
  if (CURATED[dd]) { entries[dd] = CURATED[dd]; continue; }
  // Derive: glow is the bright accent -> primary; a lighter glow -> highlight;
  // color (usually deeper) -> accent. Base-skin splash is the champion's own.
  entries[dd] = { m: glow, h: lighten(glow, 0.3), a: darken(color, 0.12), splash: `${dd}_0` };
  needSplash.push(dd);
}

const order = Object.keys(entries).sort();
const rows = order.map((dd) => {
  const e = entries[dd];
  const skin = e.skin ? `skin: ${JSON.stringify(e.skin)}, ` : "";
  return `  ${JSON.stringify(dd).padEnd(16)}: { ${skin}m: "${e.m}", h: "${e.h}", a: "${e.a}", splash: "${e.splash}" },`;
}).join("\n");

const out = `// ─────────────────────────────────────────────────────────────────────────────
//  skinThemes.js — per-champion skin palettes + splash for the Forge theme.
//  GENERATED by helpers/gen-skin-themes.mjs — do not edit by hand; edit the
//  generator (CURATED overrides there) and re-run it.
//   • 10 curated champions carry palettes hand-sampled from a specific skin's
//     splash art, with that skin's bundled splash.
//   • Every other champion derives its palette from its own color/glow and uses
//     its own base-skin splash (<dd>_0). Splashes live in public/skins/*.jpg.
//  Keyed by Data Dragon id (champ.dd). When the Forge theme is active and a
//  champion is selected, the app re-skins accents to this palette and drops the
//  splash behind the hero (dimmed, never obscuring).
// ─────────────────────────────────────────────────────────────────────────────
export const SKIN_THEMES = {
${rows}
};

export const skinThemeOf = (dd) => SKIN_THEMES[dd] || null;
`;

fs.writeFileSync(path.join(root, "src/data/skinThemes.js"), out);
fs.writeFileSync(path.join(root, "helpers/.skin-splash-list.txt"), needSplash.join("\n"));
console.log(`wrote src/data/skinThemes.js — ${order.length} champions (${order.length - needSplash.length} curated, ${needSplash.length} derived)`);
console.log(`base splashes to fetch: ${needSplash.length} (helpers/.skin-splash-list.txt)`);
