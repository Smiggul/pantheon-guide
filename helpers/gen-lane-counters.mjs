// ─────────────────────────────────────────────────────────────────────────────
//  gen-lane-counters.mjs — who actually beats each champion in its lane?
//
//  Writes src/data/laneCounters.js from lolalytics' build pages (Emerald+, the
//  bundled patch). Each champion-role page embeds its lane matchup table:
//    enemy[<lane>] = [[championKey, winRate, delta1, delta2, pick%, games], ...]
//  winRate is THIS champion's win rate against that opponent. The champions it
//  loses to most are its counters. They are ranked by delta2 (the matchup win
//  rate measured against what both champions normally win, so a strong champion
//  doesn't top every list just for being strong), and need MIN_GAMES games.
//
//  The champ-select panel uses this for "Counter picks": your lane opponent is
//  known, so its row lists the picks that beat it, with their win rate.
//
//  Report-only data from an unofficial source: run it by hand each patch
//  (`npm run gen:counters`), never in CI. Pages are cached per patch under
//  .scratch/counters/cache/<patch>/ (gitignored); a rerun reuses them.
//    --force   refetch every page
// ─────────────────────────────────────────────────────────────────────────────
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { mainObject } from "./lolalytics-page.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FORCE = process.argv.includes("--force");
const ver = fs.readFileSync(path.join(ROOT, "public", "ddragon", "version.txt"), "utf8").trim();
const patch = ver.split(".").slice(0, 2).join(".");                // 16.23.1 -> 16.23
const { CHAMPS } = await import(pathToFileURL(path.join(ROOT, "src", "data", "champs", "index.js")).href);
const { CHAMP_KEYS } = await import(pathToFileURL(path.join(ROOT, "src", "data", "lcuData.js")).href);
const DD_BY_KEY = Object.fromEntries(Object.entries(CHAMP_KEYS).map(([dd, k]) => [String(k), dd]));

const LANE = { Top: "top", Jungle: "jungle", Mid: "middle", Bot: "bottom", Support: "support" };
const SLUG = { MonkeyKing: "wukong" };
// A matchup is listed only with max(MIN_GAMES, MIN_SHARE of the role's games): 150 flat let
// 170-game oddities (Tristana into Zed) outrank 1,300-game matchups.
const MIN_GAMES = 200;
const MIN_SHARE = 0.005;
const KEEP = 8;          // counters kept per champion-role
const CACHE = path.join(ROOT, ".scratch", "counters", "cache", patch);
fs.mkdirSync(CACHE, { recursive: true });
const sleep = (ms) => new Promise((ok) => setTimeout(ok, ms));
const r1 = (x) => Math.round(x * 10) / 10;

async function pageOf(dd, lane) {
  const file = path.join(CACHE, `${dd}-${lane}.json`);
  if (!FORCE && fs.existsSync(file)) return JSON.parse(fs.readFileSync(file, "utf8"));
  const slug = SLUG[dd] || dd.toLowerCase();
  const url = `https://lolalytics.com/lol/${slug}/build/?lane=${lane}&tier=emerald_plus&patch=${patch}`;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0" } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const m = mainObject(await res.text());
      if (!m?.header) throw new Error("no embedded data");
      const rows = (m.enemy?.[lane] || []).filter((r) => Array.isArray(r) && r.length >= 6 && typeof r[5] === "number");
      const out = { n: m.header.n ?? 0, rows: rows.map((r) => [String(r[0]), r[1], r[3], r[5]]) };   // key, wr, delta2, games
      fs.writeFileSync(file, JSON.stringify(out));
      await sleep(700);
      return out;
    } catch (e) {
      if (attempt === 3) { console.warn(`  ${dd} ${lane}: ${e.message}`); return null; }
      await sleep(2000 * attempt);
    }
  }
}

const out = {};
const missing = [];
for (const c of CHAMPS) {
  for (const role of Object.keys(c.roles || {})) {
    const lane = LANE[role];
    if (!lane) continue;
    const p = await pageOf(c.dd, lane);
    if (!p || !p.rows.length) { missing.push(`${c.dd} ${role}`); continue; }
    const list = p.rows
      // ...and the counter must actually win the lane: delta2 alone rates Ezreal a Jinx counter at
      // 46.4% (he does better vs her than he usually does, but still loses).
      .filter(([k, wr, , n]) => DD_BY_KEY[k] && DD_BY_KEY[k] !== c.dd && n >= Math.max(MIN_GAMES, MIN_SHARE * p.n) && wr < 50)
      .sort((a, b) => a[2] - b[2])                                  // most negative delta2 first
      .slice(0, KEEP)
      .filter(([, , d2]) => d2 < 0)                                 // only real counters
      .map(([k, wr, d2, n]) => [DD_BY_KEY[k], r1(100 - wr), r1(-d2), n]); // the counter's win rate, its edge, games
    if (list.length) out[`${c.dd}|${role}`] = list;
  }
}

const today = new Date().toISOString().slice(0, 10);
const body = `// GENERATED by helpers/gen-lane-counters.mjs (npm run gen:counters) — do not edit by hand.
// Source: lolalytics build pages, patch ${patch}, Emerald+, fetched ${today}. Report-only source:
// regenerate each patch. Key "<dd>|<role>" = the champion you face in that lane; each row is
// [counter dd, counter's win rate vs them %, edge (delta2, points), games], best counter first.
${missing.length ? `// No data: ${missing.join(", ")}\n` : ""}export const COUNTERS_PATCH = ${JSON.stringify(patch)};
export const COUNTERS_FETCHED = ${JSON.stringify(today)};
export const LANE_COUNTERS = {
${Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};

// Counters to \`dd\` playing \`role\`, best first: [{dd, wr, edge, games}].
export function laneCountersOf(dd, role) {
  return (LANE_COUNTERS[\`\${dd}|\${role}\`] || []).map(([c, wr, edge, games]) => ({ dd: c, wr, edge, games }));
}
`;
fs.writeFileSync(path.join(ROOT, "src", "data", "laneCounters.js"), body);
console.log(`gen-lane-counters: ${Object.keys(out).length} champion-roles with counters, patch ${patch}; ${missing.length} without data`);
