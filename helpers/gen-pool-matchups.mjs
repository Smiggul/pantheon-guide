// ─────────────────────────────────────────────────────────────────────────────
//  gen-pool-matchups.mjs — which of MY champions should I play into this lane opponent?
//
//  The owner's personal pick check (2026-11-23): for each champion in his pool, the
//  win rate against every lane opponent, from lolalytics' lane matchup table on each
//  pool champion's build page (patch from version.txt), in his bracket (Iron+Bronze)
//  and at Emerald+. Champ select shows the pool ranked for the locked lane opponent.
//
//    node helpers/gen-pool-matchups.mjs Pantheon:Top Volibear:Top Mordekaiser:Top Volibear:Jungle ...
//  With no arguments it uses POOL below. Writes src/data/poolMatchups.js.
//  Report-only, unofficial source: regenerate by hand each patch, never in CI.
// ─────────────────────────────────────────────────────────────────────────────
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { mainObject } from "./lolalytics-page.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const POOL = ["Pantheon:Top", "Volibear:Top", "Mordekaiser:Top", "Pantheon:Jungle", "Volibear:Jungle", "MonkeyKing:Jungle"];
const pool = (process.argv.slice(2).length ? process.argv.slice(2) : POOL).map((s) => s.split(":"));
const ver = fs.readFileSync(path.join(ROOT, "public", "ddragon", "version.txt"), "utf8").trim();
const patch = ver.split(".").slice(0, 2).join(".");
const { CHAMP_KEYS } = await import(pathToFileURL(path.join(ROOT, "src", "data", "lcuData.js")).href);
const byKey = Object.fromEntries(Object.entries(CHAMP_KEYS).map(([dd, k]) => [String(k), dd]));
const LANE = { Top: "top", Jungle: "jungle", Mid: "middle", Bot: "bottom", Support: "support" };
const slug = (dd) => (dd === "MonkeyKing" ? "wukong" : dd.toLowerCase());
const sleep = (ms) => new Promise((ok) => setTimeout(ok, ms));

async function table(dd, lane, tier) {
  const res = await fetch(`https://lolalytics.com/lol/${slug(dd)}/build/?lane=${lane}&tier=${tier}&patch=${patch}`, { headers: { "User-Agent": "Mozilla/5.0" } });
  const m = mainObject(await res.text());
  await sleep(700);
  const o = {};
  for (const r of m?.enemy?.[lane] || []) if (Array.isArray(r) && byKey[r[0]]) o[byKey[r[0]]] = { wr: r[1], n: r[5] };
  return o;
}

// out[role][opponent][poolChamp] = [lowWr, lowGames, emeraldWr, emeraldGames]
const out = {};
for (const [dd, role] of pool) {
  const lane = LANE[role];
  const [hi, br, ir] = [await table(dd, lane, "emerald_plus"), await table(dd, lane, "bronze"), await table(dd, lane, "iron")];
  for (const foe of new Set([...Object.keys(hi), ...Object.keys(br), ...Object.keys(ir)])) {
    if (foe === dd) continue;
    const low = [br[foe], ir[foe]].filter(Boolean), ln = low.reduce((s, x) => s + x.n, 0);
    const lwr = ln ? Math.round((10 * low.reduce((s, x) => s + x.wr * x.n, 0)) / ln) / 10 : null;
    ((out[role] ||= {})[foe] ||= {})[dd] = [lwr, ln, hi[foe]?.wr ?? null, hi[foe]?.n || 0];
  }
  console.log(`  ${dd} ${role}: ${Object.keys(hi).length} opponents`);
}

const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(ROOT, "src", "data", "poolMatchups.js"),
`// GENERATED by helpers/gen-pool-matchups.mjs — do not edit by hand. The owner's champion pool,
// lolalytics patch ${patch}, fetched ${today}. POOL_MATCHUPS[role][opponent][poolChamp] =
// [win rate Iron+Bronze, games Iron+Bronze, win rate Emerald+, games Emerald+].
export const POOL = ${JSON.stringify(pool.map(([dd, role]) => ({ dd, role })))};
export const POOL_PATCH = ${JSON.stringify(patch)};
export const POOL_MATCHUPS = ${JSON.stringify(out)};

// The pool ranked into one lane opponent, leaving out champions that can't be picked
// (\`exclude\`: banned, or taken by another player). Uses the Iron+Bronze win rate when every
// option has MIN_LOW games there, else Emerald+. A gap under CLOSE points is a toss-up.
// With one option left it is simply that one (no comparison).
const MIN_LOW = 150, CLOSE = 1.5;
export function poolPick(role, foe, exclude = new Set()) {
  const rows = Object.entries(POOL_MATCHUPS[role]?.[foe] || {})
    .filter(([dd]) => !exclude.has(dd))
    .map(([dd, [lwr, ln, hwr, hn]]) => ({ dd, lwr, ln, hwr, hn }));
  if (rows.length === 0) return null;
  const low = rows.every((r) => r.lwr != null && r.ln >= MIN_LOW);
  const key = low ? "lwr" : "hwr";
  const ranked = rows.filter((r) => r[key] != null && (low || r.hn >= MIN_LOW)).sort((a, b) => b[key] - a[key]);
  if (ranked.length === 0) return null;
  const close = ranked.length > 1 && ranked[0][key] - ranked[1][key] < CLOSE;
  return { bracket: low ? "Iron–Bronze" : "Emerald+", key, ranked, close };
}
`);
console.log(`gen-pool-matchups: ${pool.length} pool entries, patch ${patch}`);
