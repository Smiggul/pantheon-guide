// ─────────────────────────────────────────────────────────────────────────────
//  helpers/gen-champ-skins.mjs
//  Generates src/data/champSkins.js — per-champion splash-bearing skin numbers
//  (base + real skins; chroma variants "Skin (Colour)" excluded, they reuse the
//  parent splash). Pinned to public/ddragon/version.txt so it matches the
//  bundled assets. Run after a patch (alongside setup_ddragon / gen-lcu-data):
//    node helpers/gen-champ-skins.mjs
// ─────────────────────────────────────────────────────────────────────────────
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ver = fs.readFileSync(path.join(root, "public/ddragon/version.txt"), "utf8").trim();
const themes = fs.readFileSync(path.join(root, "src/data/skinThemes.js"), "utf8");
const dds = [...themes.matchAll(/^\s*"([A-Za-z0-9]+)"\s*:/gm)].map((m) => m[1]);
console.log(`patch ${ver} — ${dds.length} champions`);

async function fetchSkins(dd) {
  const url = `https://ddragon.leagueoflegends.com/cdn/${ver}/data/en_US/champion/${dd}.json`;
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${dd} ${r.status}`);
  const d = await r.json();
  const champ = d.data[Object.keys(d.data)[0]];
  const nums = champ.skins.filter((s) => !s.name.includes("(")).map((s) => s.num);
  if (!nums.includes(0)) nums.unshift(0);
  return nums;
}

const map = {};
const batch = 12;
for (let i = 0; i < dds.length; i += batch) {
  const slice = dds.slice(i, i + batch);
  const res = await Promise.allSettled(slice.map(fetchSkins));
  slice.forEach((dd, j) => {
    map[dd] = res[j].status === "fulfilled" ? res[j].value : [0];
    if (res[j].status !== "fulfilled") console.error("!!", dd, res[j].reason?.message);
  });
}

const keys = Object.keys(map).sort();
const rows = keys.map((dd) => `  ${JSON.stringify(dd).padEnd(16)}: [${map[dd].join(",")}],`).join("\n");
const body = `// ─────────────────────────────────────────────────────────────────────────────
//  champSkins.js — GENERATED by helpers/gen-champ-skins.mjs. Do not edit by hand.
//  Per-champion splash-bearing skin numbers (base + real skins; chroma variants
//  excluded — they reuse the parent splash). Keyed by champ.dd. The Forge theme
//  picks a random one each time a champion is selected and loads its splash from
//  Data Dragon; the bundled base splash (public/skins/<dd>_0.jpg) is the offline
//  fallback.
// ─────────────────────────────────────────────────────────────────────────────
export const CHAMP_SKINS = {
${rows}
};

export const randomSkinNum = (dd) => {
  const list = CHAMP_SKINS[dd];
  if (!list || !list.length) return 0;
  return list[Math.floor(Math.random() * list.length)];
};
`;
fs.writeFileSync(path.join(root, "src/data/champSkins.js"), body);
const total = keys.reduce((n, k) => n + map[k].length, 0);
console.log(`wrote src/data/champSkins.js — ${keys.length} champions, ${total} splash skins (avg ${(total / keys.length).toFixed(1)})`);
