// Writes build/version.nsh so the installer shows the version players read
// (0.21.1.4) rather than the three-number one package.json ships (0.21.104).
// Runs first in `npm run dist:win`; build/installer.nsh includes the result.
import { readFileSync, writeFileSync } from "node:fs";
import { shownVersion } from "../src/data/appVersion.js";

const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const shown = shownVersion(version);
if (!/^[0-9.]+$/.test(shown)) throw new Error(`Unexpected version: ${shown}`);

writeFileSync(
  new URL("../build/version.nsh", import.meta.url),
  `; Generated by helpers/gen-installer-version.mjs from package.json ${version}. Do not edit.\n!define FRGE_SHOWN_VERSION "${shown}"\n`,
);
console.log(`Installer shows FRGE.GG ${shown} (ships as ${version}).`);
