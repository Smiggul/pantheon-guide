// Regenerates src/data/lcuData.js from authoritative sources.
//   Runes/styles/shards: CommunityDragon perks + perkstyles (Riot perk ids)
//   Items/champ keys:     DDragon latest (CANONICAL Riot ids — the project's own
//                         item.json uses non-canonical ids, unusable for the LCU)
// Run after a patch that changes runes or items:  node helpers/gen-lcu-data.mjs
import fs from "node:fs";
import { pathToFileURL } from "node:url";

const CD = "https://raw.communitydragon.org/latest/plugins/rcp-be-lol-game-data/global/default/v1";
const j = async (u) => (await fetch(u)).json();

const perks = await j(`${CD}/perks.json`);
const styles = (await j(`${CD}/perkstyles.json`)).styles;
// Pin to the ddragon version the project's assets are on (public/ddragon/version.txt),
// NOT always-latest — otherwise a new patch silently drifts the export ids away
// from the runtime item.json/images. Bump version.txt via setup_ddragon.py first.
const ver = fs.readFileSync("public/ddragon/version.txt", "utf8").trim();
const full = (await j(`https://ddragon.leagueoflegends.com/cdn/${ver}/data/en_US/item.json`)).data;
const champs = (await j(`https://ddragon.leagueoflegends.com/cdn/${ver}/data/en_US/champion.json`)).data;

const STYLE = {}; for (const s of styles) STYLE[s.name.trim()] = s.id;
const RUNE = {}; for (const p of perks) if (p.name && !(p.id >= 5001 && p.id <= 5013)) RUNE[p.name.trim()] = p.id;
// stat shards keyed by the project's naming (two need aliases to Riot's names)
const SHARD = { "Adaptive Force":5008,"Attack Speed":5005,"Ability Haste":5007,"Move Speed":5010,
  "Health":5011,"Health (scaling)":5001,"Tenacity":5013,"Armor":5002,"Magic Resist":5003 };
const CHAMP = {}; for (const v of Object.values(champs)) CHAMP[v.id] = Number(v.key);

const idByName = {}; for (const [id, v] of Object.entries(full)) if (!(v.name in idByName)) idByName[v.name] = id;

// gather every build item + first-core item used across the roster (+ each
// champion's in-file alt builds — champ.altBuilds:{ Role:[{corePath,sideItems}] })
const mod = await import(pathToFileURL("src/data/champs/index.js").href);
const used = new Set(), firstCore = new Set();
const eatRole = (r) => {
  if (typeof r.corePath === "string") { const p = r.corePath.split("›").map((s) => s.trim()); p.forEach((s) => used.add(s)); if (p[0]) firstCore.add(p[0]); }
  if (Array.isArray(r.sideItems)) r.sideItems.forEach((s) => used.add(s));
  for (const cell of Object.values(r.data || {})) for (const side of ["ahead", "behind"]) for (const e of (cell[side] || [])) if (e?.name) used.add(e.name);
};
for (const c of mod.CHAMPS) {
  for (const r of (c.roles ? Object.values(c.roles) : (c.data ? [c] : []))) eatRole(r);
  for (const list of Object.values(c.altBuilds || {})) for (const b of list) eatRole(b);
}

["Doran's Blade","Doran's Ring","Doran's Shield","Doran's Bow","Doran's Helm",
 "Health Potion","Refillable Potion","Corrupting Potion","Amplifying Tome","Ruby Crystal","Cloth Armor",
 "Cull","Dark Seal","Tear of the Goddess","Control Ward","Stealth Ward","Farsight Alteration","Oracle Lens",
 "Plated Steelcaps","Mercury's Treads","Sorcerer's Shoes","Berserker's Greaves","Ionian Boots of Lucidity",
 "Boots of Swiftness","Gluttonous Greaves","Symbiotic Soles","Boots","Long Sword",
 "Scorchclaw Pup","Gustwalker Hatchling","Mosstomper Seedling"].forEach((n) => used.add(n));

// First-back = the ~1000g building block of the first core item. Take the
// priciest component within budget; if a component is over budget (e.g. The
// Brutalizer 1337 under Voltaic Cyclosword), descend into it so we land on the
// real early buy (Serrated Dirk) rather than an unaffordable epic.
const FB_MAX = 1350;
function firstBackFor(itemName) {
  const rootId = idByName[itemName]; if (!rootId || !full[rootId]?.from?.length) return null;
  let best = null, bestGold = -1;
  const walk = (id, depth) => {
    const e = full[id]; if (!e?.from?.length || depth > 3) return;
    for (const cid of e.from) {
      const c = full[cid]; if (!c) continue;
      const g = c.gold?.total ?? 0;
      if (g <= FB_MAX) { if (g > bestGold) { bestGold = g; best = c.name; } }
      else walk(cid, depth + 1);
    }
  };
  walk(rootId, 0);
  return best;
}
const FB = {};
for (const n of firstCore) { const fb = firstBackFor(n); if (fb) { FB[n] = fb; used.add(fb); } }

const ITEM = {}; for (const n of used) { const id = idByName[n]; if (id) ITEM[n.toLowerCase()] = Number(id); }
if (idByName["Blade of The Ruined King"]) ITEM["blade of the ruined king"] = Number(idByName["Blade of The Ruined King"]);

const lit = (o) => Object.entries(o).sort((a, b) => String(a[0]).localeCompare(String(b[0])))
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");

fs.writeFileSync("src/data/lcuData.js",
`// GENERATED by helpers/gen-lcu-data.mjs — do not edit by hand.
// Source: CommunityDragon perks/perkstyles + DDragon ${ver} item.json/champion.json.
// Rune/style/shard ids are Riot perk ids; item ids and champ keys are CANONICAL
// Riot ids (the project's own item.json uses non-canonical ids, unusable for the
// LCU). ITEM_IDS keys are lowercased for case-insensitive lookup.
export const STYLE_IDS = {
${lit(STYLE)}
};
export const RUNE_IDS = {
${lit(RUNE)}
};
export const SHARD_IDS = {
${lit(SHARD)}
};
export const FIRST_BACK = {
${lit(FB)}
};
export const CHAMP_KEYS = {
${lit(CHAMP)}
};
export const ITEM_IDS = {
${lit(ITEM)}
};
`);
console.log(`Wrote src/data/lcuData.js — ddragon ${ver}: ${Object.keys(STYLE).length} styles, ${Object.keys(RUNE).length} runes, ${Object.keys(SHARD).length} shards, ${Object.keys(FB).length} first-back, ${Object.keys(CHAMP).length} champ keys, ${Object.keys(ITEM).length} items.`);
